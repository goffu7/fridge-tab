const DICTS: Record<Lang, Dict> = { en, th };

const initial = (): Lang => {
  try {
    const saved = localStorage.getItem("ft.lang");
    if (saved === "en" || saved === "th") return saved;
  } catch {
    /* private mode */
  }
  return navigator.language?.toLowerCase().startsWith("th") ? "th" : "en";
};

let lang = initial();
const listeners = new Set<() => void>();
document.documentElement.lang = lang;

export function setLang(l: Lang) {
  lang = l;
  try {
    localStorage.setItem("ft.lang", l);
  } catch {
    /* private mode */
  }
  document.documentElement.lang = l;
  listeners.forEach((fn) => fn());
}

/** Current strings, for code outside React (toasts, stored drafts). */
export const t = () => DICTS[lang];

export const useLang = () =>
  useSyncExternalStore(
    (l) => (listeners.add(l), () => listeners.delete(l)),
    () => lang,
  );

/** Current strings; re-renders the component when the language changes. */
export const useT = () => DICTS[useLang()];

/** "14 Oct" / "14 ต.ค." */
export const shortDate = (iso: string) => new Date(`${iso}T12:00:00`).toLocaleDateString(t().locale, { day: "numeric", month: "short" });
/** "Oct" / "ต.ค." */
export const shortMonth = (iso: string) => new Date(`${iso}T12:00:00`).toLocaleDateString(t().locale, { month: "short" });
